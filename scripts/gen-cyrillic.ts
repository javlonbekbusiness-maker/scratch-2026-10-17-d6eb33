/**
 * Regenerates src/i18n/messages/uz-Cyrl.ts from uz.ts via transliteration.
 * Run after changing uz.ts:  npx tsx scripts/gen-cyrillic.ts
 * Hand-edit the output afterwards if a word transliterates awkwardly.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import uz from '../src/i18n/messages/uz';
import { latinToCyrillic } from '../src/lib/translit';

function walk(o: unknown): unknown {
  if (typeof o === 'string') return latinToCyrillic(o);
  return Object.fromEntries(Object.entries(o as object).map(([k, v]) => [k, walk(v)]));
}

const out = `// Generated by scripts/gen-cyrillic.ts — safe to hand-edit.
import type { Messages } from './uz';

const uzCyrl: Messages = ${JSON.stringify(walk(uz), null, 2)};

export default uzCyrl;
`;
writeFileSync(join(__dirname, '../src/i18n/messages/uz-Cyrl.ts'), out);
console.log('uz-Cyrl.ts written');
